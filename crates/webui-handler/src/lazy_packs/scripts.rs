//! The generated module that loads the custom element scripts of lazy regions.

use super::{LazyPackFile, LazyScript};
use std::ffi::OsStr;
use std::path::{Component, Path, Prefix};

/// File name of the generated module that registers lazy-region scripts.
///
/// Builds write it to the generated-modules directory. Applications import it
/// once, through their bundler, instead of `@microsoft/webui-framework/lazy.js`.
pub const LAZY_SCRIPTS_MODULE: &str = "lazy.webui.js";

/// File name of the TypeScript declarations that builds write next to
/// [`LAZY_SCRIPTS_MODULE`].
///
/// TypeScript resolves an import of `./lazy.webui.js` to this file, which
/// brings in the lazy runtime's types, so applications get the element API
/// the runtime adds (`$rendered()`, `$prefetch()`) without `allowJs`.
pub const LAZY_SCRIPTS_DECLARATION: &str = "lazy.webui.d.ts";

/// Content of [`LAZY_SCRIPTS_DECLARATION`], the same for every build.
pub const LAZY_SCRIPTS_DECLARATION_SOURCE: &str =
    "// Generated by WebUI. Do not edit.\nimport '@microsoft/webui-framework/lazy.js';\n";

const HEADER: &str = "// Generated by WebUI. Do not edit.\n\
import { defineLazyScripts } from '@microsoft/webui-framework/lazy.js';\n\n";

/// Render [`LAZY_SCRIPTS_MODULE`] for a build's lazy-region packs.
///
/// Each region with [`LazyPackFile::scripts`] maps its tags to dynamic imports
/// of their modules, so the application's bundler splits, resolves, and caches
/// them. Regions and tags are sorted and strings are JSON-escaped, so equal
/// inputs produce identical bytes. Regions without scripts are omitted; when
/// none remain the module registers an empty map, so applications can always
/// import it.
///
/// Returns `None` when the build has no lazy regions.
#[must_use]
pub fn render_scripts_module(packs: &[LazyPackFile]) -> Option<String> {
    if packs.is_empty() {
        return None;
    }
    let mut regions: Vec<&LazyPackFile> = packs
        .iter()
        .filter(|pack| !pack.scripts.is_empty())
        .collect();
    regions.sort_unstable_by(|left, right| left.region.cmp(&right.region));
    let estimate: usize = regions
        .iter()
        .map(|pack| {
            pack.region.len()
                + 12
                + pack
                    .scripts
                    .iter()
                    .map(|script| script.tag.len() + script.specifier.len() + 32)
                    .sum::<usize>()
        })
        .sum();
    let mut module = String::with_capacity(HEADER.len() + 32 + estimate);
    module.push_str(HEADER);
    if regions.is_empty() {
        module.push_str("defineLazyScripts({});\n");
        return Some(module);
    }
    module.push_str("defineLazyScripts({\n");
    let mut scripts: Vec<&LazyScript> = Vec::new();
    for pack in regions {
        module.push_str("  ");
        push_json_string(&mut module, &pack.region);
        module.push_str(": {\n");
        scripts.clear();
        scripts.extend(&pack.scripts);
        scripts.sort_unstable_by(|left, right| left.tag.cmp(&right.tag));
        for script in &scripts {
            module.push_str("    ");
            push_json_string(&mut module, &script.tag);
            module.push_str(": () => import(");
            push_json_string(&mut module, &script.specifier);
            module.push_str("),\n");
        }
        module.push_str("  },\n");
    }
    module.push_str("});\n");
    Some(module)
}

/// Append `value` as a JSON string literal, which is also a JavaScript string.
pub(super) fn push_json_string(output: &mut String, value: &str) {
    output.push('"');
    for ch in value.chars() {
        match ch {
            '"' => output.push_str("\\\""),
            '\\' => output.push_str("\\\\"),
            '\n' => output.push_str("\\n"),
            '\r' => output.push_str("\\r"),
            '\t' => output.push_str("\\t"),
            '\u{08}' => output.push_str("\\b"),
            '\u{0c}' => output.push_str("\\f"),
            control if control < ' ' => {
                let code = u32::from(control);
                output.push_str("\\u00");
                for digit in [code >> 4, code & 0xf] {
                    output.push(char::from_digit(digit, 16).unwrap_or('0'));
                }
            }
            other => output.push(other),
        }
    }
    output.push('"');
}

/// The relative ES module specifier for `module`, imported from a file in
/// `from_dir`.
///
/// Both paths must be absolute, or both relative to the same directory. The
/// result uses `/` separators, starts with `./` or `../` as bundlers expect of
/// relative imports, and keeps the module's extension. `.` and `..` resolve
/// lexically, the way bundlers resolve relative specifiers. On Windows, drive
/// letters and names compare case-insensitively, and verbatim (`\\?\`) paths
/// match their ordinary form.
///
/// Returns `None` when no relative path exists, such as between Windows
/// drives, or when a path component is not valid UTF-8.
#[must_use]
pub fn module_specifier(from_dir: &Path, module: &Path) -> Option<String> {
    let from = Normalized::new(from_dir)?;
    let to = Normalized::new(module)?;
    if from.absolute != to.absolute || !same_prefix(from.prefix, to.prefix) {
        return None;
    }
    let common = from
        .parts
        .iter()
        .zip(&to.parts)
        .take_while(|(left, right)| same_part(**left, **right))
        .count();
    let ups = &from.parts[common..];
    let downs = &to.parts[common..];
    // Leaving `from_dir` through a leading `..` would need the parent's name.
    if downs.is_empty() || ups.iter().any(|part| matches!(part, Part::Parent)) {
        return None;
    }
    let mut specifier = String::with_capacity(
        2 + ups.len() * 3
            + downs
                .iter()
                .map(|part| match part {
                    Part::Parent => 3,
                    Part::Name(name) => name.len() + 1,
                })
                .sum::<usize>(),
    );
    if ups.is_empty() {
        specifier.push_str("./");
    }
    for _ in ups {
        specifier.push_str("../");
    }
    for (index, part) in downs.iter().enumerate() {
        if index != 0 {
            specifier.push('/');
        }
        specifier.push_str(match part {
            Part::Parent => "..",
            Part::Name(name) => name,
        });
    }
    Some(specifier)
}

/// One lexically normalized path component.
#[derive(Clone, Copy)]
enum Part<'a> {
    /// A `..` that leaves the start of a relative path.
    Parent,
    Name(&'a str),
}

/// A path with `.` removed and `..` applied to the preceding name.
struct Normalized<'a> {
    prefix: Option<Prefix<'a>>,
    absolute: bool,
    parts: Vec<Part<'a>>,
}

impl<'a> Normalized<'a> {
    fn new(path: &'a Path) -> Option<Self> {
        let mut normalized = Self {
            prefix: None,
            absolute: false,
            parts: Vec::new(),
        };
        for component in path.components() {
            match component {
                Component::Prefix(prefix) => normalized.prefix = Some(prefix.kind()),
                Component::RootDir => normalized.absolute = true,
                Component::CurDir => {}
                Component::ParentDir => match normalized.parts.last() {
                    Some(Part::Name(_)) => {
                        normalized.parts.pop();
                    }
                    // `..` at a root stays at the root.
                    _ if normalized.absolute => {}
                    _ => normalized.parts.push(Part::Parent),
                },
                Component::Normal(name) => normalized.parts.push(Part::Name(name.to_str()?)),
            }
        }
        Some(normalized)
    }
}

fn same_part(left: Part<'_>, right: Part<'_>) -> bool {
    match (left, right) {
        (Part::Parent, Part::Parent) => true,
        (Part::Name(left), Part::Name(right)) => same_name(left, right),
        _ => false,
    }
}

fn same_name(left: &str, right: &str) -> bool {
    if cfg!(windows) {
        left.eq_ignore_ascii_case(right)
    } else {
        left == right
    }
}

/// Whether two prefixes name one location, treating `\\?\C:` as `C:` and
/// `\\?\UNC\server\share` as `\\server\share`.
fn same_prefix(left: Option<Prefix<'_>>, right: Option<Prefix<'_>>) -> bool {
    match (left.map(Location::of), right.map(Location::of)) {
        (None, None) => true,
        (Some(Location::Disk(left)), Some(Location::Disk(right))) => {
            left.eq_ignore_ascii_case(&right)
        }
        (Some(Location::Share(left_server, left_share)), Some(Location::Share(server, share))) => {
            left_server.eq_ignore_ascii_case(server) && left_share.eq_ignore_ascii_case(share)
        }
        (Some(Location::Other(left)), Some(Location::Other(right))) => left == right,
        _ => false,
    }
}

/// A prefix with its verbatim and ordinary spellings merged.
enum Location<'a> {
    Disk(u8),
    Share(&'a OsStr, &'a OsStr),
    Other(Prefix<'a>),
}

impl<'a> Location<'a> {
    fn of(prefix: Prefix<'a>) -> Self {
        match prefix {
            Prefix::Disk(drive) | Prefix::VerbatimDisk(drive) => Self::Disk(drive),
            Prefix::UNC(server, share) | Prefix::VerbatimUNC(server, share) => {
                Self::Share(server, share)
            }
            other => Self::Other(other),
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::lazy_packs::LazyTrigger;

    fn pack(region: &str, scripts: &[(&str, &str)]) -> LazyPackFile {
        LazyPackFile {
            file_name: format!("{}.0123456789abcdef.json", region.replace(':', "_")),
            content: "{}".to_owned(),
            region: region.to_owned(),
            owner: region.split("::").next().unwrap_or_default().to_owned(),
            trigger: LazyTrigger::Intent,
            components: scripts.iter().map(|(tag, _)| (*tag).to_owned()).collect(),
            scripts: scripts
                .iter()
                .map(|(tag, specifier)| LazyScript {
                    tag: (*tag).to_owned(),
                    specifier: (*specifier).to_owned(),
                })
                .collect(),
            brotli_bytes: None,
        }
    }

    #[test]
    fn module_maps_each_region_to_sorted_dynamic_imports() {
        let packs = [
            pack(
                "settings-dialog::lazy:@0",
                &[
                    ("theme-picker", "../src/theme-picker/theme-picker.js"),
                    ("account-form", "@contoso/forms/account-form.js"),
                ],
            ),
            pack("app-shell::lazy:@1", &[]),
            pack(
                "app-shell::lazy:@0",
                &[("settings-panel", "../src/settings-panel/settings-panel.ts")],
            ),
        ];
        let expected = concat!(
            "// Generated by WebUI. Do not edit.\n",
            "import { defineLazyScripts } from '@microsoft/webui-framework/lazy.js';\n",
            "\n",
            "defineLazyScripts({\n",
            "  \"app-shell::lazy:@0\": {\n",
            "    \"settings-panel\": () => import(\"../src/settings-panel/settings-panel.ts\"),\n",
            "  },\n",
            "  \"settings-dialog::lazy:@0\": {\n",
            "    \"account-form\": () => import(\"@contoso/forms/account-form.js\"),\n",
            "    \"theme-picker\": () => import(\"../src/theme-picker/theme-picker.js\"),\n",
            "  },\n",
            "});\n",
        );
        assert_eq!(render_scripts_module(&packs).as_deref(), Some(expected));
        let mut reversed = packs.clone();
        reversed.reverse();
        for pack in &mut reversed {
            pack.scripts.reverse();
        }
        assert_eq!(render_scripts_module(&reversed).as_deref(), Some(expected));
    }

    #[test]
    fn module_without_scripts_registers_an_empty_map_and_no_regions_has_no_module() {
        let expected = concat!(
            "// Generated by WebUI. Do not edit.\n",
            "import { defineLazyScripts } from '@microsoft/webui-framework/lazy.js';\n",
            "\n",
            "defineLazyScripts({});\n",
        );
        assert_eq!(
            render_scripts_module(&[pack("app-shell::lazy:@0", &[])]).as_deref(),
            Some(expected)
        );
        assert_eq!(render_scripts_module(&[]), None);
    }

    #[test]
    fn declaration_sits_beside_the_module_and_imports_the_runtime_types() {
        // TypeScript reads `./lazy.webui.d.ts` for an import of `./lazy.webui.js`.
        assert_eq!(
            LAZY_SCRIPTS_MODULE.strip_suffix(".js"),
            LAZY_SCRIPTS_DECLARATION.strip_suffix(".d.ts")
        );
        assert_eq!(
            LAZY_SCRIPTS_DECLARATION_SOURCE,
            concat!(
                "// Generated by WebUI. Do not edit.\n",
                "import '@microsoft/webui-framework/lazy.js';\n",
            )
        );
    }

    #[test]
    fn module_strings_are_json_escaped() {
        let module = render_scripts_module(&[pack(
            "app-shell::lazy:@0",
            &[("odd-card", "./quote\"back\\slash\u{1}.js")],
        )])
        .unwrap_or_default();
        assert!(
            module.contains(r#"import("./quote\"back\\slash\u0001.js")"#),
            "{module}"
        );
    }

    fn specifier(from: &str, module: &str) -> Option<String> {
        module_specifier(Path::new(from), Path::new(module))
    }

    #[test]
    fn specifiers_are_relative_with_forward_slashes() {
        assert_eq!(
            specifier("/app/dist", "/app/src/settings-panel/settings-panel.ts").as_deref(),
            Some("../src/settings-panel/settings-panel.ts")
        );
        assert_eq!(
            specifier("/app", "/app/settings-panel.js").as_deref(),
            Some("./settings-panel.js")
        );
        assert_eq!(
            specifier("/app/./dist/../.webui", "/app/src/../lib/x-card.ts").as_deref(),
            Some("../lib/x-card.ts")
        );
        assert_eq!(
            specifier("/app/a/b/c", "/app/x-card.js").as_deref(),
            Some("../../../x-card.js")
        );
        assert_eq!(specifier("/app", "/app"), None);
        assert_eq!(specifier("/app", "app/x-card.js"), None);
    }

    #[test]
    fn virtual_paths_resolve_from_their_shared_root() {
        assert_eq!(specifier("", "x-card.ts").as_deref(), Some("./x-card.ts"));
        assert_eq!(
            specifier(".webui", "components/x-card.js").as_deref(),
            Some("../components/x-card.js")
        );
        assert_eq!(
            specifier("out", "../shared/x-card.js").as_deref(),
            Some("../../shared/x-card.js")
        );
        // The directory above a relative root has no name to return through.
        assert_eq!(specifier("../out", "x-card.js"), None);
    }

    #[cfg(windows)]
    #[test]
    fn windows_specifiers_normalize_separators_case_and_verbatim_prefixes() {
        assert_eq!(
            specifier(
                r"C:\repo\dist",
                r"C:\repo\src\settings-panel\settings-panel.ts"
            )
            .as_deref(),
            Some("../src/settings-panel/settings-panel.ts")
        );
        assert_eq!(
            specifier(
                r"c:\Repo\dist",
                r"\\?\C:\repo\node_modules\pkg\x-card\x-card.js"
            )
            .as_deref(),
            Some("../node_modules/pkg/x-card/x-card.js")
        );
        assert_eq!(
            specifier(r"\\server\share\app", r"\\?\UNC\server\share\lib\x.js").as_deref(),
            Some("../lib/x.js")
        );
        assert_eq!(specifier(r"C:\repo\dist", r"D:\repo\src\x.ts"), None);
    }
}
