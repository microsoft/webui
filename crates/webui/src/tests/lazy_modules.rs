use super::*;

const SHELL_INDEX: &str = "<html><head></head><body><app-shell></app-shell></body></html>";

/// An owner with a scripted eager child, a lazy region that introduces a
/// scripted `settings-panel` and a scriptless `plain-note`, and a nested
/// region that introduces a scripted `theme-picker`.
fn scripted_regions_app() -> TempDir {
    create_app_dir(&[
        ("index.html", SHELL_INDEX),
        (
            "app-shell/app-shell.html",
            concat!(
                "<eager-badge></eager-badge><dialog>",
                r#"<if condition="open" lazy><settings-panel></settings-panel><plain-note></plain-note><eager-badge></eager-badge>"#,
                r#"<if condition="advanced" lazy="idle"><theme-picker></theme-picker></if></if>"#,
                "</dialog>",
            ),
        ),
        ("app-shell/app-shell.ts", "export {};"),
        ("eager-badge/eager-badge.html", "<span>Badge</span>"),
        ("eager-badge/eager-badge.ts", "export {};"),
        (
            "settings-panel/settings-panel.html",
            "<button @click=\"{save()}\">Save</button>",
        ),
        ("settings-panel/settings-panel.ts", "export {};"),
        ("settings-panel/settings-panel.js", "export {};"),
        ("plain-note/plain-note.html", "<p>Note</p>"),
        ("theme-picker/theme-picker.html", "<select></select>"),
        ("theme-picker/theme-picker.js", "export {};"),
    ])
}

fn lazy_options(app: &Path) -> BuildOptions {
    BuildOptions {
        plugin: Some(Plugin::WebUI),
        ..default_options(app)
    }
}

fn pack<'a>(result: &'a BuildResult, region: &str) -> &'a LazyPackFile {
    result
        .lazy_pack_files
        .iter()
        .find(|pack| pack.region == region)
        .unwrap()
}

#[test]
fn generated_module_imports_the_scripted_components_each_region_introduces() {
    let app = scripted_regions_app();
    let mut options = lazy_options(app.path());
    options.modules_out = Some(app.path().join(".webui"));
    let result = build(options).unwrap();

    let module = result.lazy_scripts_module.as_ref().unwrap();
    assert_eq!(module.file_name, "lazy.webui.js");
    assert_eq!(module.declaration.file_name, "lazy.webui.d.ts");
    assert_eq!(
        module.declaration.content,
        concat!(
            "// Generated by WebUI. Do not edit.\n",
            "import '@microsoft/webui-framework/lazy.js';\n",
        )
    );
    assert_eq!(
        module.content,
        concat!(
            "// Generated by WebUI. Do not edit.\n",
            "import { defineLazyScripts } from '@microsoft/webui-framework/lazy.js';\n",
            "\n",
            "defineLazyScripts({\n",
            "  \"app-shell::lazy:@0\": {\n",
            "    \"settings-panel\": () => import(\"../settings-panel/settings-panel.ts\"),\n",
            "  },\n",
            "  \"app-shell::lazy:@1\": {\n",
            "    \"theme-picker\": () => import(\"../theme-picker/theme-picker.js\"),\n",
            "  },\n",
            "});\n",
        )
    );
    assert!(!module.content.contains('\\'), "{}", module.content);

    let outer = pack(&result, "app-shell::lazy:@0");
    assert_eq!(outer.owner, "app-shell");
    assert_eq!(outer.trigger, LazyTrigger::Intent);
    // The owner already loads `eager-badge`; `plain-note` has no client code.
    assert_eq!(outer.components, ["plain-note", "settings-panel"]);
    assert_eq!(
        outer.scripts,
        [LazyScript {
            tag: "settings-panel".to_string(),
            specifier: "../settings-panel/settings-panel.ts".to_string(),
        }]
    );
    let nested = pack(&result, "app-shell::lazy:@1");
    assert_eq!(nested.trigger, LazyTrigger::Idle);
    assert_eq!(nested.components, ["theme-picker"]);
    assert!(result.warnings.is_empty(), "{:?}", result.warnings);
}

#[test]
fn generated_module_is_deterministic_and_defaults_to_app_relative_specifiers() {
    let app = scripted_regions_app();
    let first = build(lazy_options(app.path())).unwrap();
    let second = build(lazy_options(app.path())).unwrap();
    let module = first.lazy_scripts_module.unwrap();
    assert_eq!(Some(&module), second.lazy_scripts_module.as_ref());
    assert!(module
        .content
        .contains(r#""settings-panel": () => import("./settings-panel/settings-panel.ts"),"#));
    assert!(module
        .content
        .contains(r#""theme-picker": () => import("./theme-picker/theme-picker.js"),"#));
}

#[test]
fn component_module_mappings_override_discovered_modules() {
    let app = scripted_regions_app();
    let mut options = lazy_options(app.path());
    options.component_modules = BTreeMap::from([
        (
            "settings-panel".to_string(),
            "@contoso/settings/panel.js".to_string(),
        ),
        (
            "plain-note".to_string(),
            "./vendor/plain-note.js".to_string(),
        ),
    ]);
    let result = build(options).unwrap();
    let module = &result.lazy_scripts_module.as_ref().unwrap().content;
    assert!(
        module.contains(r#""settings-panel": () => import("@contoso/settings/panel.js"),"#),
        "{module}"
    );
    assert!(
        module.contains(r#""plain-note": () => import("./vendor/plain-note.js"),"#),
        "{module}"
    );
    assert!(!module.contains("settings-panel.ts"), "{module}");
    let outer = pack(&result, "app-shell::lazy:@0");
    let tags: Vec<&str> = outer
        .scripts
        .iter()
        .map(|script| script.tag.as_str())
        .collect();
    assert_eq!(tags, ["plain-note", "settings-panel"]);
}

