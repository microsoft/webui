/// A page whose header shows `user-badge` at startup and whose `/reports`
/// route renders `report-chart`. `app-shell`'s region uses both, the route
/// component itself, and a `settings-panel` that only the region uses.
fn startup_app() -> TempDir {
    create_app_dir(&[
        (
            "index.html",
            concat!(
                "<html><head></head><body><site-header></site-header><app-shell></app-shell>",
                r#"<route path="/reports" component="reports-page" exact />"#,
                "</body></html>",
            ),
        ),
        (
            "site-header/site-header.html",
            r#"<if condition="signedIn"><user-badge></user-badge></if>"#,
        ),
        ("site-header/site-header.ts", "export {};"),
        ("user-badge/user-badge.html", "<span>User</span>"),
        ("user-badge/user-badge.ts", "export {};"),
        (
            "app-shell/app-shell.html",
            concat!(
                r#"<if condition="open" lazy><user-badge></user-badge><report-chart></report-chart>"#,
                "<reports-page></reports-page><settings-panel></settings-panel></if>",
            ),
        ),
        ("app-shell/app-shell.ts", "export {};"),
        (
            "reports-page/reports-page.html",
            "<report-chart></report-chart>",
        ),
        ("reports-page/reports-page.ts", "export {};"),
        ("report-chart/report-chart.html", "<canvas></canvas>"),
        ("report-chart/report-chart.ts", "export {};"),
        ("settings-panel/settings-panel.html", "<form></form>"),
        ("settings-panel/settings-panel.ts", "export {};"),
    ])
}

#[test]
fn regions_skip_the_scripts_the_page_loads_at_startup() {
    let app = startup_app();
    let result = build(lazy_options(app.path())).unwrap();
    let region = pack(&result, "app-shell::lazy:@0");
    // The pack still carries every template its owner does not guarantee.
    assert_eq!(
        region.components,
        [
            "report-chart",
            "reports-page",
            "settings-panel",
            "user-badge"
        ]
    );
    // `user-badge` loads at startup, through a non-lazy condition. Route
    // components load with route partials, so a region still loads them.
    let tags: Vec<&str> = region
        .scripts
        .iter()
        .map(|script| script.tag.as_str())
        .collect();
    assert_eq!(tags, ["report-chart", "reports-page", "settings-panel"]);
    let module = &result.lazy_scripts_module.as_ref().unwrap().content;
    assert!(!module.contains("user-badge"), "{module}");
    assert!(
        module.contains(r#""settings-panel": () => import("#),
        "{module}"
    );
    assert!(result.warnings.is_empty(), "{:?}", result.warnings);
}

