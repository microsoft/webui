#[test]
fn unknown_and_invalid_component_module_mappings_are_reported() {
    let app = scripted_regions_app();
    let mut options = lazy_options(app.path());
    options.component_modules =
        BTreeMap::from([("settings-panl".to_string(), "./panel.js".to_string())]);
    let result = build(options.clone()).unwrap();
    let warning = result
        .warnings
        .iter()
        .find(|warning| warning.error_code() == Some(webui_parser::codes::UNKNOWN_COMPONENT_MODULE))
        .unwrap();
    assert!(warning
        .help_text()
        .unwrap()
        .contains("did you mean <settings-panel>"));

    for (tag, specifier) in [
        ("SettingsPanel", "./panel.js"),
        ("settings-panel", "./a b.js"),
    ] {
        options.component_modules = BTreeMap::from([(tag.to_string(), specifier.to_string())]);
        let error = build(options.clone()).unwrap_err();
        let WebUIError::ComponentModules(diagnostic) = error else {
            panic!("expected a component module error, got {error}");
        };
        assert_eq!(
            diagnostic.error_code(),
            Some(webui_parser::codes::INVALID_COMPONENT_MODULE)
        );
    }
}

#[test]
fn metafile_reports_lazy_packs_without_component_assets() {
    let app = scripted_regions_app();
    let mut options = lazy_options(app.path());
    options.modules_out = Some(app.path().join(".webui"));
    options.metafile = true;
    let result = build(options.clone()).unwrap();

    let metafile: serde_json::Value =
        serde_json::from_str(result.metafile.as_deref().unwrap()).unwrap();
    assert_eq!(metafile["inputs"], serde_json::json!({}));
    assert_eq!(metafile["outputs"], serde_json::json!({}));
    let entries = metafile["lazyPacks"].as_array().unwrap();
    assert_eq!(entries.len(), 2);
    let paths: Vec<&str> = entries
        .iter()
        .map(|entry| entry["path"].as_str().unwrap())
        .collect();
    let mut sorted = paths.clone();
    sorted.sort_unstable();
    assert_eq!(paths, sorted);
    for entry in entries {
        let pack = pack(&result, entry["region"].as_str().unwrap());
        assert_eq!(entry["path"], format!("_webui/packs/{}", pack.file_name));
        assert_eq!(entry["owner"], "app-shell");
        assert_eq!(entry["trigger"], pack.trigger.as_str());
        assert_eq!(entry["bytes"], pack.content.len());
        let brotli = pack.brotli_bytes.unwrap();
        assert!(brotli > 0 && brotli < pack.content.len());
        assert_eq!(entry["brotliBytes"], brotli);
        assert_eq!(entry["hash"], pack.hash());
        let scripts: Vec<&str> = pack
            .scripts
            .iter()
            .map(|script| script.specifier.as_str())
            .collect();
        assert_eq!(entry["scripts"], serde_json::json!(scripts));
    }
    let outer = entries
        .iter()
        .find(|entry| entry["region"] == "app-shell::lazy:@0")
        .unwrap();
    assert_eq!(outer["trigger"], "intent");
    assert_eq!(
        outer["scripts"],
        serde_json::json!(["../settings-panel/settings-panel.ts"])
    );

    options.metafile = false;
    let without = build(options).unwrap();
    assert!(without.metafile.is_none());
    assert!(without
        .lazy_pack_files
        .iter()
        .all(|pack| pack.brotli_bytes.is_none()));
}

