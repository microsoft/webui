#[test]
fn build_to_disk_publishes_the_generated_module_to_the_modules_directory() {
    let app = scripted_regions_app();
    let out = TempDir::new().unwrap();
    build_to_disk(lazy_options(app.path()), out.path()).unwrap();
    let path = out.path().join(LAZY_SCRIPTS_MODULE);
    let written = fs::read_to_string(&path).unwrap();
    let canonical_out = std::path::absolute(out.path()).unwrap();
    let canonical_app = std::path::absolute(app.path()).unwrap();
    let expected = webui_handler::lazy_packs::module_specifier(
        &canonical_out,
        &canonical_app
            .join("settings-panel")
            .join("settings-panel.ts"),
    )
    .unwrap();
    assert!(
        written.contains(&format!("import(\"{expected}\")")),
        "{written}"
    );
    let modified = fs::metadata(&path).unwrap().modified().unwrap();
    let declaration = out.path().join(LAZY_SCRIPTS_DECLARATION);
    assert_eq!(
        fs::read_to_string(&declaration).unwrap(),
        "// Generated by WebUI. Do not edit.\nimport '@microsoft/webui-framework/lazy.js';\n"
    );
    let declared = fs::metadata(&declaration).unwrap().modified().unwrap();
    build_to_disk(lazy_options(app.path()), out.path()).unwrap();
    assert_eq!(fs::metadata(&path).unwrap().modified().unwrap(), modified);
    assert_eq!(
        fs::metadata(&declaration).unwrap().modified().unwrap(),
        declared
    );

    let modules = TempDir::new().unwrap();
    let mut options = lazy_options(app.path());
    options.modules_out = Some(modules.path().to_path_buf());
    let separate_out = TempDir::new().unwrap();
    build_to_disk(options, separate_out.path()).unwrap();
    assert!(modules.path().join(LAZY_SCRIPTS_MODULE).is_file());
    assert!(modules.path().join(LAZY_SCRIPTS_DECLARATION).is_file());
    assert!(!separate_out.path().join(LAZY_SCRIPTS_MODULE).exists());
    assert!(!separate_out.path().join(LAZY_SCRIPTS_DECLARATION).exists());
    assert!(separate_out.path().join(PACK_OUTPUT_DIR).is_dir());
}
